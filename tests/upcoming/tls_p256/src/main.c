static void result(const char *name, bool ok) { printf("%-13s %s\n", name, ok ? "PASS" : "FAIL"); }

int main(void)
{
    uint8_t public_key[65], secret[32], signature[64], bad[65];
    bool pub, ecdh, sign, verify, reject;
    if (!lwip_start()) return 1;

    pub = tls_p256_publickey(public_key, initiator_private) &&
          memcmp(public_key, initiator_public, sizeof public_key) == 0;
    ecdh = tls_p256_secret(secret, initiator_private, responder_public) &&
           memcmp(secret, shared_expected, sizeof secret) == 0;
    sign = tls_p256_sign(signature, sample_hash, sign_private) &&
           memcmp(signature, sample_signature, sizeof signature) == 0;
    verify = tls_p256_publickey(public_key, sign_private) &&
             tls_p256_verify(sample_signature, sample_hash, public_key);
    memcpy(bad, responder_public, sizeof bad); bad[64] ^= 1;
    memset(secret, 0, sizeof secret);
    reject = !tls_p256_publickey(public_key, secret) &&
             !tls_p256_secret(secret, initiator_private, bad);

    os_ClrHome();
    puts("P-256 reference");
    result("public key", pub); result("ECDH secret", ecdh);
    result("RFC6979 sign", sign); result("ECDSA verify", verify);
    result("bad inputs", reject);
    puts("\nPress any key");
    os_GetKey();
    return (pub && ecdh && sign && verify && reject) ? 0 : 1;
}
