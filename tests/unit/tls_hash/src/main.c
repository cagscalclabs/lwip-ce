static uint8_t seq_buf[500];

static void fill_seq(size_t n)
{
    for (size_t i = 0; i < n; i++)
        seq_buf[i] = (uint8_t)(i & 0xff);
}

static bool sha384_check(const uint8_t *msg, size_t len, const uint8_t *expected)
{
    struct tls_hash_context hctx;
    uint8_t out[TLS_SHA384_DIGEST_LEN];
    bool ok = tls_hash_context_init(&hctx, TLS_HASH_SHA384);
    if (ok)
    {
        tls_hash_update(&hctx, msg, len);
        tls_hash_digest(&hctx, out);
        ok = memcmp(out, expected, TLS_SHA384_DIGEST_LEN) == 0;
    }
    tls_hash_clear(&hctx);
    return ok;
}

static bool sha384_stream_check(const uint8_t *msg, const size_t *parts, size_t nparts,
                                const uint8_t *expected)
{
    struct tls_hash_context hctx;
    uint8_t out[TLS_SHA384_DIGEST_LEN];
    size_t off = 0;
    bool ok = tls_hash_context_init(&hctx, TLS_HASH_SHA384);
    for (size_t i = 0; ok && i < nparts; i++)
    {
        tls_hash_update(&hctx, msg + off, parts[i]);
        off += parts[i];
    }
    if (ok)
    {
        tls_hash_update(&hctx, msg + off, 0);
        tls_hash_digest(&hctx, out);
        ok = memcmp(out, expected, TLS_SHA384_DIGEST_LEN) == 0;
    }
    tls_hash_clear(&hctx);
    return ok;
}

