    ok &= tls_hkdf_expand_label(TLS_HASH_SHA384, sats, 48,
                                "key", 3, NULL, 0, sak, 32);
    ok &= tls_hkdf_expand_label(TLS_HASH_SHA384, sats, 48,
                                "iv", 2, NULL, 0, sai, 12);

    ok &= memcmp(early, expected_early, 48) == 0;
    ok &= memcmp(hs, expected_hs, 48) == 0;
    ok &= memcmp(th, expected_th, 48) == 0;
    ok &= memcmp(chts, expected_chts, 48) == 0;
    ok &= memcmp(shts, expected_shts, 48) == 0;
    ok &= memcmp(ckey, expected_ckey, 32) == 0;
    ok &= memcmp(civ, expected_civ, 12) == 0;
    ok &= memcmp(vd, expected_vd, 48) == 0;
    ok &= memcmp(cak, expected_cak, 32) == 0;
    ok &= memcmp(skey, expected_skey, 32) == 0;
    ok &= memcmp(siv, expected_siv, 12) == 0;
