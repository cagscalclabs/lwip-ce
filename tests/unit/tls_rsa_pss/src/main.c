{
    if (!lwip_start()) return 1;

    os_ClrHome();

    /* Run tests */
    bool test1 = test_pss_verify();
    bool test2 = test_certverify_pss_verify();

    /* Output results */
    os_ClrHome();
    printf("Test 1 (Verify): %s\n", test1 ? "success" : "fail");
    printf("Test 2 (CertV): %s\n", test2 ? "success" : "fail");
    os_GetKey();

    return (test1 && test2) ? 0 : 1;
}
