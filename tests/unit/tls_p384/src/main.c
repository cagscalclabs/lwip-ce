static bool test_sign_a(void)
{
    uint8_t sig[96], sig2[96];
    if (!tls_p384_sign(sig, hash1, priv_a)) return false;
    if (memcmp(sig, sig_a_h1, 96) != 0) return false;
    /* RFC 6979 is deterministic: sign again, same r/s. */
    if (!tls_p384_sign(sig2, hash1, priv_a)) return false;
    return memcmp(sig, sig2, 96) == 0;
}

static bool test_verify_a(void)
{
    return tls_p384_verify(sig_a_h1, hash1, pub_a);
}

