static bool test_reject_bad(void)
{
    uint8_t pub[97], bad_sig[96], bad_pub[97], ss[48];
    bool ok = true;

    if (!tls_p384_publickey(pub, priv_a)) return false;
    memcpy(bad_sig, sig_a_h1, 96);
    bad_sig[5] ^= 0x10;
    ok = ok && !tls_p384_verify(bad_sig, hash1, pub);
    ok = ok && !tls_p384_verify(sig_a_h1, hash2, pub);

    memcpy(bad_pub, pub_a, 97);
    bad_pub[96] ^= 0x01;
    ok = ok && !tls_p384_secret(ss, priv_a, bad_pub);
    ok = ok && !tls_p384_verify(sig_a_h1, hash1, bad_pub);

    memcpy(bad_pub, pub_a, 97);
    bad_pub[0] = 0x02;
    ok = ok && !tls_p384_secret(ss, priv_a, bad_pub);

    memcpy(bad_pub, pub_a, 97);
    memcpy(bad_pub + 1, p_bytes, 48);
    ok = ok && !tls_p384_secret(ss, priv_a, bad_pub);

    memset(bad_pub, 0, 97);
    bad_pub[0] = 0x04;
    ok = ok && !tls_p384_secret(ss, priv_a, bad_pub);
    return ok;
}

static bool test_reject_range(void)
{
    uint8_t pub[97], bad_sig[96];
    bool ok = true;

    if (!tls_p384_publickey(pub, priv_a)) return false;
    memset(bad_sig, 0, 96);
    memcpy(bad_sig + 48, sig_a_h1 + 48, 48);
    ok = ok && !tls_p384_verify(bad_sig, hash1, pub);

    memcpy(bad_sig, sig_a_h1, 48);
    memset(bad_sig + 48, 0, 48);
    ok = ok && !tls_p384_verify(bad_sig, hash1, pub);

    memcpy(bad_sig, n_bytes, 48);
    memcpy(bad_sig + 48, sig_a_h1 + 48, 48);
    ok = ok && !tls_p384_verify(bad_sig, hash1, pub);

    memcpy(bad_sig, sig_a_h1, 48);
    memcpy(bad_sig + 48, n_bytes, 48);
    ok = ok && !tls_p384_verify(bad_sig, hash1, pub);
    return ok;
}


