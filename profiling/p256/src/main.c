static const uint8_t zero_hash[32];

static bool check_edges(void)
{
    bool ok = true;
    for (uint8_t i = 0; i < sizeof ek / sizeof ek[0]; i++) {
        bool r = tls_p256_publickey(pk2, ek[i]) && memcmp(pk2, epub[i], 65) == 0;
        if (!r) dbg_printf("edge k[%u] FAIL\n", i);
        ok = ok && r;
    }
    {   /* x(P) = 0 peer point */
        bool r = tls_p256_secret(ss, priv, xzero_pt) && memcmp(ss, xzero_ss, 32) == 0;
        if (!r) dbg_printf("x=0 ECDH FAIL\n");
        ok = ok && r;
    }
    {   /* hash = 0 -> u1 = 0 in verify (scalar k = 0) */
        bool r = tls_p256_sign(sig, zero_hash, sign_private) &&
                 tls_p256_publickey(pk2, sign_private) &&
                 tls_p256_verify(sig, zero_hash, pk2);
        if (!r) dbg_printf("zero-hash sign/verify FAIL\n");
        ok = ok && r;
    }
    return ok;
}

