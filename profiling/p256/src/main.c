/* Random operand < p.  mode picks a byte distribution that stresses
 * carries (0xFF-heavy) as well as uniform bytes; a top byte <= 0xFE
 * keeps the value below p = 0xFFFFFFFF00000001... */
static void rnd_fe(uint8_t *x, uint8_t mode)
{
    static const uint8_t pick[4] = { 0x00, 0xFF, 0xFE, 0x01 };
    for (uint8_t i = 0; i < 32; i++) {
        uint8_t r = rnd8();
        x[i] = (mode & 1) ? pick[r & 3] : r;
        if ((mode & 2) && (r & 0x80)) x[i] = 0xFF;
    }
    if (x[31] == 0xFF) x[31] = 0xFE;
}

