/* =========================================================================
 * Timing
 * ========================================================================= */

#define TIMING_SAMPLES 16

typedef struct {
    clock_t avg;
    clock_t max_delta_pct; /* max |sample - avg| as integer percent of avg */
} op_timing_t;

typedef struct {
    op_timing_t pubkey;
    op_timing_t secret;
    op_timing_t sign;
    op_timing_t verify;
} timing_t;

static op_timing_t measure_op(clock_t samples[TIMING_SAMPLES])
{
    op_timing_t r;
    clock_t sum = 0;
    for (int i = 0; i < TIMING_SAMPLES; i++)
        sum += samples[i];
    r.avg = sum / TIMING_SAMPLES;

    clock_t max_delta = 0;
    for (int i = 0; i < TIMING_SAMPLES; i++) {
        clock_t delta = samples[i] > r.avg ? samples[i] - r.avg : r.avg - samples[i];
        if (delta > max_delta) max_delta = delta;
    }
    /* percent: (max_delta * 100) / avg, guarded against div-by-zero */
    r.max_delta_pct = r.avg ? (max_delta * 100) / r.avg : 0;
    return r;
}

static void fill_random(uint8_t *buf, size_t len)
{
    for (size_t i = 0; i < len; i++)
        buf[i] = (uint8_t)(rand() & 0xFF);
}

static void measure_timing(timing_t *t)
{
    clock_t pubkey_samples[TIMING_SAMPLES];
    clock_t secret_samples[TIMING_SAMPLES];
    clock_t sign_samples[TIMING_SAMPLES];
    clock_t verify_samples[TIMING_SAMPLES];

    uint8_t priv1[32], priv2[32];
    uint8_t pub1[65], pub2[65];
    uint8_t secret[32], h[32], sig[64];
    clock_t s, e;
    int si = 0; /* sample index, increments by 2 per ECDHE round */

    /* ECDHE timing: 8 rounds of 2 keypairs => 16 samples each for pubkey and secret */
    for (int round = 0; round < TIMING_SAMPLES / 2; round++) {
        fill_random(priv1, sizeof(priv1));
        fill_random(priv2, sizeof(priv2));

        s = clock(); tls_p256_publickey(pub1, priv1); e = clock();
        pubkey_samples[si] = e - s;

        s = clock(); tls_p256_publickey(pub2, priv2); e = clock();
        pubkey_samples[si + 1] = e - s;

        s = clock(); tls_p256_secret(secret, priv1, pub2); e = clock();
        secret_samples[si] = e - s;

        s = clock(); tls_p256_secret(secret, priv2, pub1); e = clock();
        secret_samples[si + 1] = e - s;

        si += 2;
    }
    t->pubkey = measure_op(pubkey_samples);
    t->secret = measure_op(secret_samples);

    /* ECDSA timing: collect exactly TIMING_SAMPLES valid sign+verify pairs.
     * Skip any iteration where sign fails (shouldn't happen with rfc6979_priv,
     * but guarded so a buggy impl doesn't corrupt the sample array). */
    int sign_n = 0, verify_n = 0;
    for (int attempts = 0; sign_n < TIMING_SAMPLES && attempts < TIMING_SAMPLES * 4; attempts++) {
        fill_random(h, sizeof(h));

        s = clock(); bool ok = tls_p256_sign(sig, h, rfc6979_priv); e = clock();
        if (!ok) continue;
        sign_samples[sign_n++] = e - s;

        s = clock(); tls_p256_verify(sig, h, rfc6979_pub); e = clock();
        verify_samples[verify_n++] = e - s;
    }
    t->sign   = measure_op(sign_samples);
    t->verify = measure_op(verify_samples);
}

