int main(void)
{
    bool all = true;
    bool r;

    os_ClrHome();
    printf("P-256 Contest Test Suite\n");
    printf("========================\n\n");

    printf("[ECDHE - RFC 5903 s8.1]\n");
    r = ecdhe_rfc5903_init_pubkey();    all &= r; print_result("init pubkey", r);
    r = ecdhe_rfc5903_resp_pubkey();    all &= r; print_result("resp pubkey", r);
    r = ecdhe_rfc5903_secret_init();    all &= r; print_result("secret i*Qr", r);
    r = ecdhe_rfc5903_secret_resp();    all &= r; print_result("secret r*Qi", r);

    os_GetKey();
    os_ClrHome();
    printf("[ECDSA Sign - RFC 6979 A.2.5]\n");
    r = ecdsa_rfc6979_sample_sign();    all &= r; print_result("sign 'sample'", r);
    r = ecdsa_rfc6979_test_sign();      all &= r; print_result("sign 'test'", r);

    printf("\n[ECDSA Verify - RFC 6979]\n");
    r = ecdsa_rfc6979_sample_verify();  all &= r; print_result("verify 'sample'", r);
    r = ecdsa_rfc6979_test_verify();    all &= r; print_result("verify 'test'", r);

    os_GetKey();
    os_ClrHome();
    printf("[ECDSA Verify - NIST CAVP]\n");
    r = ecdsa_cavp_verify_1();          all &= r; print_result("cavp valid 1", r);
    r = ecdsa_cavp_verify_2();          all &= r; print_result("cavp valid 2", r);
    r = ecdsa_cavp_reject_bad_sig();    all &= r; print_result("reject bad s", r);
    r = ecdsa_cavp_reject_wrong_key();  all &= r; print_result("reject bad key", r);
    r = ecdsa_cavp_reject_wrong_hash(); all &= r; print_result("reject bad hash", r);

    printf("\n[Round-trip]\n");
    r = ecdsa_roundtrip_seqhash();      all &= r; print_result("roundtrip seq", r);
    r = ecdsa_roundtrip_allff();        all &= r; print_result("roundtrip 0xFF", r);
    r = ecdsa_roundtrip_allzero();      all &= r; print_result("roundtrip 0x00", r);

    os_GetKey();
    os_ClrHome();
    printf("Overall: %s\n\n", all ? "ALL PASS" : "FAILURES PRESENT");

    if (all) {
        srand((unsigned int)clock());
        timing_t t;
        measure_timing(&t);
        printf("[Timing (n=%d)]\n", TIMING_SAMPLES);
        printf("%-10s %10s  %s\n", "Op", "Avg cyc", "Max delta%");
        printf("PublicKey  %10lu  %lu%%\n", (unsigned long)t.pubkey.avg, (unsigned long)t.pubkey.max_delta_pct);
        printf("Secret     %10lu  %lu%%\n", (unsigned long)t.secret.avg, (unsigned long)t.secret.max_delta_pct);
        printf("Sign       %10lu  %lu%%\n", (unsigned long)t.sign.avg,   (unsigned long)t.sign.max_delta_pct);
        printf("Verify     %10lu  %lu%%\n", (unsigned long)t.verify.avg, (unsigned long)t.verify.max_delta_pct);
    }

    os_GetKey();
    return 0;
}
